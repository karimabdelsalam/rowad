/** يزرع مكتبة البرامج مرة واحدة دون تكرار القوالب الموجودة */
function seed_diet_library(PDO $pdo): int
{
    $exists = $pdo->prepare('SELECT id FROM diet_templates WHERE title = ?');
    $insert = $pdo->prepare(
        'INSERT INTO diet_templates (title, category, tag, description, calories, breakfast, snack1,
         lunch, snack2, dinner, forbidden, notes, warnings) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)'
    );
    // القوالب الموجودة: تُصنَّف وتُستكمل حقولها الفارغة فقط، دون المساس بمحتوى عدّله الأخصائي
    $update = $pdo->prepare(
        "UPDATE diet_templates SET category = ?, tag = ?, description = ?, warnings = ?,
         forbidden = CASE WHEN COALESCE(forbidden, '') = '' THEN ? ELSE forbidden END WHERE id = ?"
    );

    $added = 0;
    foreach (diet_library() as $t) {
        $exists->execute([$t['title']]);
        $id = $exists->fetchColumn();
        if ($id) {
            $update->execute([
                $t['category'], $t['tag'], $t['description'], $t['warnings'] ?: null,
                $t['forbidden'] ?? null, (int)$id,
            ]);
            continue;
        }
        $insert->execute([
            $t['title'], $t['category'], $t['tag'], $t['description'], $t['calories'],
            $t['breakfast'], $t['snack1'], $t['lunch'], $t['snack2'], $t['dinner'],
            $t['forbidden'] ?? null, $t['notes'], $t['warnings'] ?: null,
        ]);
        $added++;
    }
    return $added;
}
