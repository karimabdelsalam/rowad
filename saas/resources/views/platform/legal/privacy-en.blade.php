<p>This policy explains how <b>Aqar Nova</b> handles data, in line with the Saudi Personal Data Protection Law (PDPL).</p>

<h2>1. Who is responsible</h2>
<ul>
    <li><b>Account data</b> (organization and admin name, email, mobile, subscription details): the platform is responsible.</li>
    <li><b>Organization business data</b> (owners, tenants, contracts, payments): the organization is the controller; the platform processes it on the organization's behalf and only to provide the service.</li>
</ul>

<h2>2. What we collect</h2>
<ul>
    <li>Signup, subscription and payment details.</li>
    <li>The data an organization enters in its system.</li>
    <li>Technical data needed for security: IP addresses, sign-in history and browser type.</li>
</ul>

<h2>3. How we use it</h2>
<p>To run the service, send the messages the organization asks for (SMS and email), bill, provide support, and protect accounts from unauthorized use. We do not sell data or use it for advertising.</p>

<h2>4. Separation between organizations</h2>
<p>Each organization has its own database, and users of one organization cannot reach another's data. Inside an organization each user sees what their permissions allow, and owners and tenants see only their own data.</p>

<h2>5. The AI assistant</h2>
<p>When the AI assistant is used, the question and only the data needed to answer it are sent to the AI provider (Anthropic) to produce the answer; the provider does not receive the organization's whole database. Conversations are stored in the organization's database and users can delete them.</p>

<h2>6. Service providers</h2>
<p>We use providers to run the service: hosting, the SMS provider the organization chooses, email and AI. Each only receives what it needs to do its job.</p>

<h2>7. Retention and deletion</h2>
<p>We keep data for as long as the subscription lasts. After cancellation it stays available for download for 30 days and is then permanently deleted, except what the law requires us to keep, such as invoice records.</p>

<h2>8. Security</h2>
<p>Connections are encrypted (HTTPS), passwords are hashed, backups are taken daily, and SMS verification at sign-in can be enabled.</p>

