<p>توضح هذه السياسة كيف تتعامل منصة <b>عقار نوفا</b> مع البيانات، بما يتوافق مع نظام حماية البيانات الشخصية في المملكة العربية السعودية.</p>

<h2>1. من المسؤول عن البيانات</h2>
<ul>
    <li><b>بيانات الحساب</b> (اسم المؤسسة والمدير والبريد والجوال وبيانات الاشتراك): المنصة مسؤولة عنها.</li>
    <li><b>بيانات أعمال المؤسسة</b> (الملاك والمستأجرون والعقود والدفعات): المؤسسة هي المسؤولة عنها، والمنصة تعالجها نيابة عنها ووفق تعليماتها فقط لتقديم الخدمة.</li>
</ul>

<h2>2. البيانات التي نجمعها</h2>
<ul>
    <li>بيانات التسجيل والاشتراك والدفع.</li>
    <li>البيانات التي تدخلها المؤسسة في نظامها.</li>
    <li>بيانات تقنية لازمة للأمان: عناوين IP وسجل الدخول ونوع المتصفح.</li>
</ul>

<h2>3. كيف نستخدمها</h2>
<p>لتشغيل الخدمة، وإرسال الرسائل التي تطلبها المؤسسة (SMS والبريد)، والفوترة، والدعم الفني، وحماية الحسابات من الاستخدام غير المصرح به. لا نبيع البيانات ولا نستخدمها في الإعلانات.</p>

<h2>4. الفصل بين المؤسسات</h2>
<p>لكل مؤسسة قاعدة بيانات مستقلة، ولا يستطيع مستخدمو مؤسسة الوصول إلى بيانات أخرى. داخل المؤسسة يرى كل مستخدم ما تسمح به صلاحياته، ويرى المالك والمستأجر بياناتهما فقط.</p>

<h2>5. المساعد الذكي</h2>
<p>عند استخدام المساعد الذكي يُرسل السؤال والبيانات اللازمة للإجابة عنه فقط إلى مزود خدمة الذكاء الاصطناعي (Anthropic) لمعالجتها وإرجاع الإجابة، ولا يتلقى المزود بيانات المؤسسة كاملة. تُحفظ المحادثات داخل قاعدة بيانات المؤسسة ويستطيع المستخدم حذفها.</p>

<h2>6. مزودو الخدمة</h2>
<p>نستعين بمزودين لتشغيل الخدمة: الاستضافة، ومزود الرسائل النصية الذي تختاره المؤسسة، والبريد الإلكتروني، والذكاء الاصطناعي. لا يحصل أي منهم إلا على ما يلزم لأداء خدمته.</p>

<h2>7. الحفظ والحذف</h2>
<p>نحتفظ بالبيانات طوال مدة الاشتراك. بعد إلغاء الحساب تُتاح للتنزيل 30 يومًا ثم تُحذف نهائيًا، باستثناء ما يلزم الاحتفاظ به نظامًا مثل سجلات الفواتير.</p>

<h2>8. الحماية</h2>
<p>الاتصال مشفر (HTTPS)، وكلمات المرور مشفرة، ونأخذ نسخًا احتياطية يومية، ويمكن تفعيل التحقق برمز SMS عند الدخول.</p>

