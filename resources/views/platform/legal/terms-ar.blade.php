<p>بيانات المؤسسة ملك لها. تستطيع المؤسسة تنزيل نسخة كاملة من بياناتها في أي وقت من الإعدادات. لا تبيع المنصة بيانات المؤسسات ولا تستخدمها لأي غرض غير تقديم الخدمة. تفاصيل ذلك في <a href="{{ route('central.privacy', [], false) }}">سياسة الخصوصية</a>.</p>

