    <li>بعد التجربة يستمر الحساب بسداد اشتراك الباقة المختارة شهريًا أو سنويًا. الأسعار بالريال السعودي.</li>
    <li>عند انتهاء فترة الاشتراك دون تجديد يستمر الحساب سبعة أيام سماح ثم يُوقف مؤقتًا حتى السداد، دون حذف البيانات.</li>
