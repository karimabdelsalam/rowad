<h2>1. الخدمة</h2>
<p>توفر المنصة لكل مؤسسة مشتركة لوحة لإدارة الوحدات والعقود والدفعات وحسابات الملاك والفواتير والتقارير، وبوابات للملاك والمستأجرين، وموقعًا عامًا للمؤسسة، ومساعدًا ذكيًا. تعمل كل مؤسسة على رابطها الخاص وبقاعدة بيانات مستقلة.</p>

<h2>2. الحساب والمسؤولية عنه</h2>
<ul>
