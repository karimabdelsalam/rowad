    <li>المؤسسة مسؤولة عن حسابات مستخدميها وصلاحياتهم وسرية كلمات مرورهم، وعن كل ما يتم من خلالها.</li>
    <li>المؤسسة مسؤولة عن صحة البيانات التي تدخلها وعن حصولها على موافقة الملاك والمستأجرين على معالجة بياناتهم وإرسال الرسائل إليهم وفق الأنظمة.</li>
</ul>

<h2>3. التجربة المجانية والاشتراك والدفع</h2>
<ul>
