<p>نعمل على أن تكون المنصة متاحة باستمرار ونأخذ نسخًا احتياطية يومية، وقد تتوقف الخدمة لفترات قصيرة للصيانة أو لأسباب خارجة عن إرادتنا. لا تتجاوز مسؤولية المنصة في أي حال قيمة ما دفعته المؤسسة خلال الأشهر الثلاثة السابقة للمطالبة.</p>

