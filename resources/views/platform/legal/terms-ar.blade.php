<p>المساعد الذكي أداة مساعدة تقرأ بيانات المؤسسة وتحللها ولا تعدّل شيئًا. قد تحتوي إجاباته أحيانًا على أخطاء، لذا يجب مراجعة الأرقام والقرارات المهمة قبل الاعتماد عليها. المسودات التي يكتبها (رسائل وخطابات) لا تُرسل إلا بعد مراجعة المستخدم وإرسالها بنفسه.</p>

